"""Regenerate src/ai_qa_agents/core/report/fonts.css from the Fontsource npm packages.

The report embeds its fonts (Inter variable 400-700, IBM Plex Mono 400/500/600,
latin subset) as base64 so it opens identically offline and makes no external
request. Both fonts are under the SIL Open Font License 1.1; their license
texts are copied to core/report/FONTS-LICENSE.txt.

    uv run python scripts/vendor_fonts.py      # needs npm and the npm registry
"""

from __future__ import annotations

import base64
import re
import subprocess
import sys
import tarfile
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
REPORT = ROOT / "src" / "ai_qa_agents" / "core" / "report"

PACKAGES = {
    "@fontsource-variable/inter": [("Inter", "inter-latin-wght-normal.woff2", "400 700")],
    "@fontsource/ibm-plex-mono": [
        ("IBM Plex Mono", f"ibm-plex-mono-latin-{w}-normal.woff2", w) for w in ("400", "500", "600")
    ],
}


def unicode_range(pkg: Path, file: str) -> str:
    """The unicode-range Fontsource declares for this file, from any of its CSS files."""
    pattern = re.compile(re.escape(f"./files/{file}") + r"\)[^;]*;\s*unicode-range:\s*([^;]+);")
    for css in sorted(pkg.glob("*.css")):
        match = pattern.search(css.read_text(encoding="utf-8"))
        if match:
            return match.group(1).strip()
    raise SystemExit(f"no unicode-range for {file} in {pkg}")


def unpack(package: str, workdir: Path) -> Path:
    tgz = (
        subprocess.run(
            ["npm", "pack", package, "--silent", "--pack-destination", str(workdir)],
            check=True,
            capture_output=True,
            text=True,
        )
        .stdout.strip()
        .splitlines()[-1]
    )
    dest = workdir / tgz.removesuffix(".tgz")
    with tarfile.open(workdir / tgz) as tar:
        tar.extractall(dest, filter="data")
    return dest / "package"


def main() -> int:
    blocks = [
        "/* GENERATED by scripts/vendor_fonts.py — do not edit. Fonts: SIL OFL 1.1,",
        "   see FONTS-LICENSE.txt. Latin subset, embedded so the report needs no network. */",
    ]
    licenses = []
    with tempfile.TemporaryDirectory() as tmp:
        for package, faces in PACKAGES.items():
            pkg = unpack(package, Path(tmp))
            for family, file, weight in faces:
                data = base64.b64encode((pkg / "files" / file).read_bytes()).decode("ascii")
                blocks.append(
                    "@font-face {\n"
                    f'  font-family: "{family}";\n'
                    "  font-style: normal;\n"
                    f"  font-weight: {weight};\n"
                    "  font-display: swap;\n"
                    f'  src: url("data:font/woff2;base64,{data}") format("woff2");\n'
                    f"  unicode-range: {unicode_range(pkg, file)};\n"
                    "}"
                )
            licenses.append(f"==== {package} ====\n{(pkg / 'LICENSE').read_text(encoding='utf-8')}")
    (REPORT / "fonts.css").write_text("\n".join(blocks) + "\n", encoding="utf-8")
    (REPORT / "FONTS-LICENSE.txt").write_text("\n\n".join(licenses), encoding="utf-8")
    size = (REPORT / "fonts.css").stat().st_size // 1024
    print(f"fonts.css written ({size} KB)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
